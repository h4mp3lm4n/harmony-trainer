MT.t = function (key, vars) {
  const dict = MT.I18N[MT.state.lang] || MT.I18N.de;
  let str = dict[key];
  if (str == null) str = MT.I18N.de[key] || key;
  if (vars && typeof str === 'string') {
    Object.keys(vars).forEach(k => {
      str = str.split('{' + k + '}').join(vars[k]);
    });
  }
  return str;
};

MT.loc = function (obj, arg) {
  if (obj == null) return '';
  if (typeof obj === 'function') obj = obj(arg != null ? arg : MT.state.key);
  if (typeof obj === 'string') return obj;
  return obj[MT.state.lang] != null ? obj[MT.state.lang] : (obj.de || '');
};
